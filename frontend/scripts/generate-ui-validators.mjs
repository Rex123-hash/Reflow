#!/usr/bin/env node
/** Generate CSP-safe standalone Ajv validators for presentation resources. */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import prettier from "prettier";

const here = dirname(fileURLToPath(import.meta.url));
const SPEC = resolve(here, "../src/app/contract/ui-openapi.json");
const OUT = resolve(here, "../src/app/contract/uiValidators.ts");
const resources = [
  "OverviewView",
  "ObjectivesView",
  "RecoveryCaseView",
  "EvidencePageView",
  "ExecutionEventsView",
  "OperatorContextView",
];

const openApi = JSON.parse(readFileSync(SPEC, "utf8"));
const ajv = new Ajv2020({
  allErrors: true,
  strict: false,
  code: { source: true, esm: true, lines: true },
});
ajv.addSchema(openApi, "reflow-ui-openapi");

const references = {};
for (const name of resources) {
  const id = `reflow-${name}`;
  ajv.addSchema({
    $id: id,
    $ref: `reflow-ui-openapi#/components/schemas/${name}`,
  });
  references[name] = id;
}

const generated = await prettier.format(
  `// @ts-nocheck -- generated by scripts/generate-ui-validators.mjs\n/* oxlint-disable */\n${standaloneCode(ajv, references)}`,
  { parser: "typescript" },
);

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    // Missing output is stale output.
  }
  if (current !== generated) {
    console.error("Generated UI validators are stale. Run npm run validators:generate.");
    process.exit(1);
  }
} else {
  writeFileSync(OUT, generated);
}
