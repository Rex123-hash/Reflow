/** Generate isolated P2F types and CSP-safe validators from Python-owned schemas. */
import { readFileSync, writeFileSync } from "node:fs";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import prettier from "prettier";

const spec = JSON.parse(
  readFileSync(
    new URL("../../docs/operator-openapi.json", import.meta.url),
    "utf8",
  ),
);
function typeOf(s) {
  if (s.$ref) return s.$ref.split("/").at(-1);
  if ("const" in s) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map(JSON.stringify).join(" | ");
  if (s.anyOf) return s.anyOf.map(typeOf).join(" | ");
  if (s.type === "array") return `(${typeOf(s.items)})[]`;
  if (s.type === "object")
    return `{${Object.entries(s.properties ?? {})
      .map(
        ([key, value]) =>
          `${key}${(s.required ?? []).includes(key) ? "" : "?"}: ${typeOf(value)};`,
      )
      .join("\n")}}`;
  return (
    {
      string: "string",
      integer: "number",
      number: "number",
      boolean: "boolean",
      null: "null",
    }[s.type] ?? "unknown"
  );
}
const types = Object.entries(spec.components.schemas)
  .map(([name, s]) => `export type ${name} = ${typeOf(s)};`)
  .join("\n");
const ajv = new Ajv2020({
  allErrors: true,
  strict: false,
  code: { source: true, esm: true, lines: true },
});
ajv.addSchema(spec, "operator-contract");
ajv.addSchema({
  $id: "operator-response",
  $ref: "operator-contract#/components/schemas/OperatorResponse",
});
const validator = standaloneCode(ajv, {
  validateOperatorResponse: "operator-response",
}).replace(
  /const (\w+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g,
  "const $1 = (value) => Array.from(value).length;",
);
const outputs = {
  "../src/app/operator/operatorContract.ts": `// Generated by scripts/generate-operator-contract.mjs\n${types}`,
  "../src/app/operator/operatorValidator.ts": `// @ts-nocheck -- generated standalone validator\n/* oxlint-disable */\n${validator}`,
};
for (const [path, raw] of Object.entries(outputs)) {
  const value = await prettier.format(raw, { parser: "typescript" });
  const target = new URL(path, import.meta.url);
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== value)
      throw new Error(`Stale Operator contract: ${path}`);
  } else writeFileSync(target, value);
}
